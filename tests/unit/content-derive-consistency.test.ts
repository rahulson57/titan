describe('SPEC-007 — the stored columns equal the recomputed ones', () => {
  it.each(DOCUMENTS)('holds after saving %s', async (_label, body) => {
    const result = await saveDraftContent(articleId, {
      title: 'A draft',
      bodyJson: body,
      version: 1,
    });
    expect(result.ok).toBe(true);
    await expectRowConsistent(articleId);
  });

  it.each(DOCUMENTS)('holds when %s is the FIRST save, at /editor/new', async (_label, body) => {
    // The create path writes the same four columns through a different
    // repository function (`createArticle`, not `updateArticle`). A consistency
    // guarantee proven only on the update path would leave every article's
    // first revision unverified — and for a draft that is written once and
    // published, that is the only revision there is.
    const result = await createDraftContent(authorId, { title: 'Brand new', bodyJson: body }, AT);
    expect(result.ok).toBe(true);
    if (!result.ok || !result.articleId) return;
    await expectRowConsistent(result.articleId);
  });

  it('holds across a sequence of saves, each carrying the previous version', async () => {
    // Drift is cumulative in the real failure: it appears on save N, not save
    // one. Walking the whole document list through one article, in order,
    // exercises the update path repeatedly against a row whose previous
    // contents differ every time.
    let version = 1;
    for (const [, body] of DOCUMENTS) {
      const result = await saveDraftContent(articleId, {
        title: 'A draft',
        bodyJson: body,
        version,
      });
      expect(result.ok).toBe(true);
      if (!result.ok) return;
      version = result.version;
      await expectRowConsistent(articleId);
    }
    expect(version).toBe(1 + DOCUMENTS.length);
  });

  it('holds after a publish and an unpublish', async () => {
    // Both transitions bump `version` and touch the row. Neither should
    // regenerate the body — but "should not" is exactly the kind of thing that
    // stops being true when someone adds a `bodyHtml` line to `publishArticle`.
    await saveDraftContent(articleId, {
      title: 'A draft',
      bodyJson: {
        type: 'doc',
        content: [
          {
            type: 'paragraph',
            content: [{ type: 'text', text: 'A paragraph well over the fifty-character floor.' }],
          },
        ],
      },
      version: 1,
    });
    await expectRowConsistent(articleId);

    await publishDraft(articleId, { tags: ['craft'] }, AT);
    await expectRowConsistent(articleId);

    await unpublishDraft(articleId, AT);
    await expectRowConsistent(articleId);
  });

  it('holds for a document that arrived as pasted HTML', async () => {
    const doc = parseHtmlToDoc(
      '<h1>Pasted</h1><p>Some <b>bold</b> text with a <a href="https://example.com">link</a>.</p>' +
        '<script>alert(1)</script><ul><li>one</li><li>two</li></ul>',
    );

    const result = await saveDraftContent(articleId, {
      title: 'A draft',
      bodyJson: doc,
      version: 1,
    });
    expect(result.ok).toBe(true);
    await expectRowConsistent(articleId);
  });
});

describe('SPEC-007 — what the save stores is the sanitised document', () => {
  it('stores the closed document, not the one that was posted', async () => {
    const hostile = {
      type: 'doc',
      content: [
        { type: 'script', content: [{ type: 'text', text: 'alert(1)' }] },
        { type: 'paragraph', content: [{ type: 'text', text: 'survivor' }] },
      ],
    };

    await saveDraftContent(articleId, { title: 'A draft', bodyJson: hostile, version: 1 });

    const row = await getArticleById(articleId);
    // The stored document differs from the input — which is what makes the
    // consistency check above meaningful rather than vacuous. If the save
    // stored the raw document and rendered the sanitised one, this pair of
    // assertions is where it would show.
    expect(row?.bodyJson).not.toEqual(hostile);
    expect(row?.bodyJson).toEqual(sanitizeDoc(hostile));
    expect(row?.bodyHtml).toBe(renderHtml(hostile));
    expect(row?.bodyText).toBe('survivor');
  });

  it('is stable: re-saving an unchanged document produces identical columns', async () => {
    // Idempotence at the column level. Without it, an autosave firing on a
    // document nobody edited would rewrite `bodyHtml` to something slightly
    // different every 30 seconds — invisible, and enough to make any
    // byte-comparison downstream (a cache key, a diff, this criterion) useless.
    const body = {
      type: 'doc',
      content: [
        {
          type: 'paragraph',
          content: [
            { type: 'text', text: 'stable', marks: [{ type: 'italic' }, { type: 'bold' }] },
          ],
        },
      ],
    };

    const first = await saveDraftContent(articleId, { title: 'A draft', bodyJson: body, version: 1 });
    expect(first.ok).toBe(true);
    const afterFirst = await getArticleById(articleId);

    const second = await saveDraftContent(articleId, {
      title: 'A draft',
      bodyJson: afterFirst?.bodyJson,
      version: first.ok ? first.version : 0,
    });
    expect(second.ok).toBe(true);
    const afterSecond = await getArticleById(articleId);

    expect(afterSecond?.bodyJson).toEqual(afterFirst?.bodyJson);
    expect(afterSecond?.bodyHtml).toBe(afterFirst?.bodyHtml);
    expect(afterSecond?.bodyText).toBe(afterFirst?.bodyText);
  });

  it('orders stacked marks the same way regardless of how they arrived', async () => {
    // The reason `MARK_SPECS` carries a rank. Two clients sending the same
    // marks in different orders must produce the same `bodyHtml`, or the
    // byte-equality this criterion asks for holds only for documents written by
    // whichever client happened to write them.
    const forwards = {
      type: 'doc',
      content: [
        {
          type: 'paragraph',
          content: [
            { type: 'text', text: 'x', marks: [{ type: 'bold' }, { type: 'italic' }] },
          ],
        },
      ],
    };
    const backwards = {
      type: 'doc',
      content: [
        {
          type: 'paragraph',
          content: [
            { type: 'text', text: 'x', marks: [{ type: 'italic' }, { type: 'bold' }] },
          ],
        },
      ],
    };

    expect(renderHtml(forwards)).toBe(renderHtml(backwards));
    expect(renderHtml(forwards)).toBe('<p><strong><em>x</em></strong></p>');
  });

  it('never stores a readingMinutes below one', async () => {
    // `max(1, ceil(words / 238))` — a one-line article must not read
    // "0 min read", which looks like a bug to a reader and is wrong anyway.
    await saveDraftContent(articleId, {
      title: 'A draft',
      bodyJson: { type: 'doc', content: [] },
      version: 1,
    });
    const row = await getArticleById(articleId);
    expect(row?.readingMinutes).toBe(1);
    expect(row?.bodyText).toBe('');
    await expectRowConsistent(articleId);
  });
});
