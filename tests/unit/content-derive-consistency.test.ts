/**
 * The derived columns cannot drift from the document (SPEC-007).
 *
 * Sealed criterion:
 *
 * > `bodyHtml`, `bodyText` and `readingMinutes` stored after a save exactly
 * > equal the values recomputed from `bodyJson` by `lib/content/render.ts`.
 *
 * ── What this is actually protecting against ───────────────────────────────
 * `bodyJson` is canonical (DEC-002); the other three are caches. A cache that
 * silently falls behind its source is the worst kind of defect on a reading
 * site, because nothing fails: the article page serves the PREVIOUS revision's
 * HTML while the search index and the "5 min read" badge describe the current
 * one, and the only symptom is a reader seeing an old paragraph. There is no
 * error, no log line, and no test that would notice unless it is this one.
 *
 * The criterion is therefore stated as a round trip and tested as one. Every
 * case below goes through the REAL save path — `saveDraftContent`, which is
 * what the Server Action calls — then reads the row back out of SQLite and
 * recomputes all three values from the stored `bodyJson`. Nothing is asserted
 * against a literal, because a literal would only prove that this test and the
 * renderer agree on one document.
 *
 * ── The invariant is stronger than it looks ────────────────────────────────
 * Two modules derive these values and they are deliberately different ones:
 * `lib/db/articles.ts` recomputes `bodyText`/`readingMinutes` on every write
 * via `lib/derive/reading.ts`, while `bodyHtml` is passed in, generated by
 * `lib/content/render.ts` from the closed schema. So the columns are written by
 * two different code paths on the same call, and this file is what proves those
 * two paths saw the same document.
 *
 * The subtle way that breaks: the save path stores the SANITISED document but
 * derives the HTML from the RAW one (or vice versa). The row is then internally
 * inconsistent from the very first save, and `deriveContent` returning both the
 * sanitised doc and its HTML together is the design that makes writing that bug
 * awkward. Several cases below use documents that sanitisation visibly changes,
 * so a mismatch shows up as a diff rather than as an equality that happens to
 * hold because nothing was removed.
 */

import { afterAll, beforeAll, beforeEach, describe, expect, it } from 'vitest';

import { createTestDatabase, type TestDatabase } from '../helpers/db';
import { disconnectDb } from '../../lib/db/client';
import { createUser } from '../../lib/db/users';
import { createArticle, getArticleById } from '../../lib/db/articles';
import { deriveReading } from '../../lib/derive/reading';
import { deriveContent, renderHtml } from '../../lib/content/render';
import { parseHtmlToDoc, sanitizeDoc } from '../../lib/content/schema';
import {
  createDraftContent,
  publishDraft,
  saveDraftContent,
  unpublishDraft,
} from '../../lib/content/publish';

const AT = new Date('2026-07-01T08:00:00.000Z');

let db: TestDatabase;
let authorId = '';
let articleId = '';

beforeAll(async () => {
  db = await createTestDatabase();
  process.env.DATABASE_URL = db.url;
}, 120_000);

afterAll(async () => {
  await disconnectDb();
  await db.drop();
});

beforeEach(async () => {
  await db.client.$executeRawUnsafe('DELETE FROM "ArticleTag"');
  await db.client.$executeRawUnsafe('DELETE FROM "Tag"');
  await db.client.$executeRawUnsafe('DELETE FROM "Article"');
  await db.client.$executeRawUnsafe('DELETE FROM "User"');

  const author = await createUser({
    email: 'author@titan.local',
    passwordHash: 'x',
    handle: 'author',
    name: 'The Author',
    createdAt: AT,
  });
  authorId = author.id;

  const article = await createArticle({
    authorId,
    title: 'A draft',
    bodyJson: { type: 'doc', content: [{ type: 'paragraph' }] },
    bodyHtml: '<p></p>',
    now: AT,
  });
  articleId = article.id;
});

/**
 * THE assertion of this file.
 *
 * Reads the row back from SQLite — not from the value the save returned — and
 * recomputes all three derived values from the stored `bodyJson`. Reading the
 * return value instead would test the function's own arithmetic and skip the
 * part that can actually go wrong: what reached the database.
 */
async function expectRowConsistent(id: string) {
  const row = await getArticleById(id);
  expect(row).not.toBeNull();
  if (!row) return;

  const recomputed = deriveContent(row.bodyJson);

  expect(row.bodyHtml).toBe(recomputed.bodyHtml);
  expect(row.bodyText).toBe(recomputed.bodyText);
  expect(row.readingMinutes).toBe(recomputed.readingMinutes);

  // The stored document must already be closed. If it is not, the equalities
  // above could hold while `bodyJson` carries something the schema forbids —
  // consistent, and consistently wrong.
  expect(row.bodyJson).toEqual(sanitizeDoc(row.bodyJson));

  // And the two derivation routes must agree: `lib/db/articles.ts` computes
  // bodyText/readingMinutes through `lib/derive/reading.ts`, while bodyHtml
  // comes from `lib/content/render.ts`. This is the line that proves both saw
  // the same document.
  const viaReading = deriveReading(row.bodyJson);
  expect(row.bodyText).toBe(viaReading.bodyText);
  expect(row.readingMinutes).toBe(viaReading.readingMinutes);
}

/** Documents that exercise every node and mark the schema has. */
